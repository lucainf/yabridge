#include "app-quirks.h"

#include <algorithm>
#include <system_error>

#include "../common/daw-quirks.h"

namespace fs = ghc::filesystem;

namespace app_quirks {

namespace {

/**
 * The DAW the Wine plugin host should present itself as for this plugin, if
 * any. See `host_process_name()`.
 */
std::optional<DawQuirk> daw_to_present_as(const PluginInfo& plugin_info) {
    const std::string plugin_name =
        plugin_info.windows_plugin_path_.stem().string();
    if (std::find(plugins_needing_daw_process_name.begin(),
                  plugins_needing_daw_process_name.end(),
                  plugin_name) == plugins_needing_daw_process_name.end()) {
        return std::nullopt;
    }

    // Only the DAWs in `daw_quirks` are supported, and the Linux executable
    // name we detect them by is not the Windows executable name we present
    // the host as
    const std::optional<DawQuirk> daw = detect_current_daw();
    if (!daw || !daw->presents_as_windows_executable()) {
        return std::nullopt;
    }

    return daw;
}

}  // namespace

std::optional<std::string> host_process_name(const PluginInfo& plugin_info,
                                             const fs::path& host_path,
                                             Logger& logger) {
    const std::optional<DawQuirk> daw = daw_to_present_as(plugin_info);
    if (!daw) {
        return std::nullopt;
    }

    const std::string plugin_name =
        plugin_info.windows_plugin_path_.stem().string();

    // Prefer the stub with the DAW's version information generated by
    // `tools/quirk-stubs`, installed in a `quirks` directory next to the host
    std::string presented_as(daw->windows_executable);
    std::error_code error;
    const fs::path host_binary =
        fs::canonical(fs::path(host_path.string() + ".so"), error);
    if (!error) {
        const fs::path stub = host_binary.parent_path() / "quirks" /
                              std::string(daw->windows_executable);
        if (fs::exists(stub, error)) {
            presented_as = stub.string();
        }
    }

    logger.log("App quirk: presenting the Wine plugin host as '" +
               presented_as + "' to '" + plugin_name + "'");

    return presented_as;
}

void warn_if_unavailable_in_group(const PluginInfo& plugin_info,
                                  const std::string& group,
                                  Logger& logger) {
    const std::optional<DawQuirk> daw = daw_to_present_as(plugin_info);
    if (!daw) {
        return;
    }

    logger.log(
        "WARNING: '" + plugin_info.windows_plugin_path_.stem().string() +
        "' needs the Wine plugin host to present itself as '" +
        std::string(daw->windows_executable) +
        "', but this is not possible for plugins in a plugin group since the "
        "group host process is shared with other plugins. Remove the plugin "
        "from the '" +
        group + "' group to apply this workaround.");
}

}  // namespace app_quirks
